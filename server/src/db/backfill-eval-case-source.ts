import 'dotenv/config';
import { and, eq, isNotNull, isNull } from 'drizzle-orm';
import { createDb, type Db } from './client.js';
import * as t from './schema.js';

/**
 * One-off backfill: give every pre-existing eval case the severity and category
 * of the finding it was derived from.
 *
 * `eval_cases.source_severity` / `source_category` are a SNAPSHOT written when a
 * case is created (`modules/eval/service.ts`), so cases created before those
 * columns existed carry null and render no chip. Their `source_finding_id` is
 * still there and still indexed (`eval_cases_source_finding_idx`), so for every
 * case whose finding has not been deleted the two values are recoverable exactly
 * once — which is what this script does.
 *
 * **Why a script and not SQL inside a migration.** `src/db/migrations/` is
 * generated by drizzle-kit and this repository forbids hand-editing it
 * (root `CLAUDE.md`); a hand-written `UPDATE … FROM findings` there would be
 * edited-generated output, and it would also run on databases that have no
 * findings at all. A script named after what it does can be run when it is
 * wanted, re-run safely, and read by the next person without opening a migration
 * they were told not to touch.
 *
 * **Idempotent.** Only rows where BOTH snapshot columns are null are considered,
 * so a second run touches nothing. A case whose finding is gone stays null
 * forever, which is the honest answer — there is nowhere left to read it from.
 *
 * Run it with:  `pnpm db:backfill:eval-source`
 */
export async function backfillEvalCaseSource(db: Db): Promise<{
  candidates: number;
  updated: number;
  findingMissing: number;
}> {
  /* Cases that have a source finding but no snapshot yet. `isNull` on
     `sourceSeverity` alone is the test: the two columns are written together in
     one insert, so a row can never hold one without the other. */
  const candidates = await db
    .select({
      id: t.evalCases.id,
      name: t.evalCases.name,
      sourceFindingId: t.evalCases.sourceFindingId,
    })
    .from(t.evalCases)
    .where(
      and(isNotNull(t.evalCases.sourceFindingId), isNull(t.evalCases.sourceSeverity)),
    );

  let updated = 0;
  let findingMissing = 0;

  for (const row of candidates) {
    /* Non-null by the WHERE above; narrowed here because the column's type does
       not know that. */
    const findingId = row.sourceFindingId;
    if (!findingId) continue;

    const [finding] = await db
      .select({ severity: t.findings.severity, category: t.findings.category })
      .from(t.findings)
      .where(eq(t.findings.id, findingId));

    if (!finding) {
      findingMissing += 1;
      continue;
    }

    await db
      .update(t.evalCases)
      .set({ sourceSeverity: finding.severity, sourceCategory: finding.category })
      .where(eq(t.evalCases.id, row.id));
    updated += 1;
  }

  return { candidates: candidates.length, updated, findingMissing };
}

// CLI entrypoint
if (import.meta.url === `file://${process.argv[1]}`) {
  const url = process.env.DATABASE_URL;
  if (!url) {
    console.error('DATABASE_URL is required');
    process.exit(1);
  }
  const handle = createDb(url);
  backfillEvalCaseSource(handle.db)
    .then(async (r) => {
      console.log(
        `✓ eval case source backfill: ${r.updated} updated, ` +
          `${r.findingMissing} left null (finding deleted), ${r.candidates} considered`,
      );
      await handle.close();
      process.exit(0);
    })
    .catch(async (err) => {
      console.error('✗ backfill failed:', err);
      await handle.close();
      process.exit(1);
    });
}
